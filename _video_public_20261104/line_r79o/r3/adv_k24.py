def one(jm):
    j, m = jm; p = S/f'adv_k24_{j}.json'
    if p.exists(): r = rd(p)
    else:
        msg = ASK.replace('{K11G}', view_text('op60', 'g68K11g'))
        os.environ['PUB_SRC'] = 'r2k23b'
        import importlib, pub24; importlib.reload(pub24)
        msg = msg.replace('{K23B}', pub24.view_text('op60', 'g68K23bN'))
        print('材料', j, len(msg), flush=True); r = None
        for k in range(3):
            try: r = parse(call(f'adv_k24_{j}' + ('' if not k else f'_r{k}'), msg, m, 'gpt3s', 'public24-adv')); assert r.get('prompt'); break
            except Exception as ex: print('不合格', j, repr(ex)[:150], flush=True); r = None
        if not r: return
        p.write_text(json.dumps(r, ensure_ascii=False, indent=1), encoding='utf-8')
    tpl = r['prompt'].replace('{{', '{').replace('}}', '}')
    try: prompt_lint.lint(re.sub(r'\{(BUDGET|DAGSTD|FINAL|BEADS|CURRENT)\}', '', tpl), f'adv_k24_{j}')
    except SystemExit as ex: print('泛化检查没过', j, ex, flush=True)
    (S/f'prompt_K24_{j}.txt').write_text(tpl, encoding='utf-8')
    print(f"== {j}：{(r.get('why') or '')[:600]}", flush=True)


