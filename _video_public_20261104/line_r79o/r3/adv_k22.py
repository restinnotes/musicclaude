def std():
    s = Path('D:/musicclaude/_video_public_20261104/大众版标准.md').read_text(encoding='utf-8')
    return s[s.index('## 给谁看'):s.index('## 泛化和流程')]


def dstd():
    s = Path('D:/musicclaude/_thread_evo_20261019/标准.md').read_text(encoding='utf-8')
    return s[s.index('## 内容维度'):s.index('## 不算缺点')]


def line_text(w):
    d = rd(R2/f'{w}_src.json'); out = []
    for s in d['sections']:
        out.append(f"{s['sec']}（小节 {s['bars']}；和 Center 的关系：{s.get('relation', '')}）")
        for l in s['lines']: out.append(f"  {l['id']}：{l['text']}（对应珠子：{'、'.join(l.get('beads') or [])}）")
    return d['center'], NL.join(out)


def one(jm):
    j, m = jm; p = S/f'adv_k22_{j}.json'
    if p.exists(): r = rd(p)
    else:
        c60, l60 = line_text('op60'); c61, l61 = line_text('op61')
        msg = (ASK.replace('{STD}', std()).replace('{DSTD}', dstd()).replace('{QUOTES}', QUOTES)
               .replace('{C60}', c60).replace('{L60}', l60).replace('{C61}', c61).replace('{L61}', l61)
               .replace('{B60}', blend.beads_text('op60')).replace('{K60}', view_text('op60', 'g68K11g')).replace('{K61}', view_text('op61', 'g68K11g')))
        print('材料', j, len(msg), '字', flush=True)
        r = None
        for k in range(3):
            try: r = parse(call(f'adv_k22_{j}' + ('' if not k else f'_r{k}'), msg, m, 'gpt3s', 'public24-adv')); assert r.get('plans'); break
            except Exception as ex: print('不合格', j, repr(ex)[:150], flush=True); r = None
        if not r: return
        p.write_text(json.dumps(r, ensure_ascii=False, indent=1), encoding='utf-8')
    for pl in r.get('plans') or []:
        for kind in ('screen', 'line', 'map'):
            tpl = (pl.get('prompt_' + kind) or '').replace('{{', '{').replace('}}', '}')
            if len(tpl) < 50: continue
            bare = re.sub(r'\{(BUDGET|DAGSTD|FINAL|BEADS|CURRENT|CENTER|LINE|SEGS)\}', '', tpl)
            try: prompt_lint.lint(bare, f'adv_k22_{j}_{pl.get("id")}_{kind}')
            except SystemExit as ex: print('泛化检查没过', j, pl.get('id'), kind, ex, flush=True)
            (S/f"prompt_K22_{j}_{pl.get('id')}_{kind}.txt").write_text(tpl, encoding='utf-8')
    print(f"== 顾问 {j}{NL}" + json.dumps(r.get('diagnosis'), ensure_ascii=False, indent=1)[:2500], flush=True)
    for pl in r.get('plans') or []: print(f"-- {pl.get('id')}（{pl.get('layer')}）{pl.get('hypothesis', '')[:400]}{NL}   样片：{pl.get('sample', '')[:200]}", flush=True)
    print('测法：', (r.get('measure_fix') or '')[:1200], flush=True)


if __name__ == '__main__':
    with ThreadPoolExecutor(2) as ex: list(ex.map(one, [('g6', G6), ('g56', G56)]))
