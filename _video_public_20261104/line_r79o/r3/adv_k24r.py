def issues(tag):
    out = []
    for w, nm in (('op60', '船歌'), ('op61', '幻想')):
        for j in ('g6', 'g56'):
            p = S/f'openA4_{w}_{j}_{tag}_run1.json'
            if not p.exists(): continue
            r = rd(p)
            for s in r.get('screens') or []:
                for x in s.get('issues') or []:
                    if x.get('severity') in ('中等', '严重'): out.append(f"- {nm} {s.get('sec')}（标准 {x.get('std')}）「{(x.get('quote') or '')[:40]}」：{(x.get('why') or '')[:110]}")
            for x in r.get('whole') or []:
                if x.get('severity') in ('中等', '严重'): out.append(f"- {nm} 全曲（标准 {x.get('std')}）：{(x.get('why') or '')[:140]}")
    return NL.join(out)


def faith(tag):
    out = []
    for w, nm in (('op60', '船歌'), ('op61', '幻想')):
        for f in glob.glob(str(S/f'faith_{w}_*_{tag}.json')):
            for x in rd(f).get('items') or rd(f).get('issues') or []:
                if str(x.get('severity', '严重')) == '严重' or x.get('type'):
                    out.append(f"- {nm} {x.get('sec')}：「{(x.get('screen') or x.get('quote') or '')[:40]}」←「{(x.get('source') or x.get('orig') or '')[:50]}」 {(x.get('why') or '')[:90]}")
    return NL.join(dict.fromkeys(out))


def main(j, tag, rnd, table, mine, prompt_file):
    p = S/f'adv_k24r{rnd}_{j}.json'
    if not p.exists():
        std = Path('D:/musicclaude/_video_public_20261104/大众版标准.md').read_text(encoding='utf-8')
        std = std[std.index('## 内容（屏幕稿）'):std.index('## 泛化和流程')]
        rep = os.environ.get('K24_REPAIR') == '1'
        msg = (ASK.replace('{REPAIR}', REPAIR if rep else '').replace('{REPAIRKEY}', ',"repair_prompt":"局部修补提示词"' if rep else '').replace('{TABLE}', table).replace('{ISSUES}', issues(tag)).replace('{FAITH}', faith(tag) or '（无）').replace('{MINE}', mine)
               .replace('{STD}', std).replace('{PROMPT}', (S/prompt_file).read_text(encoding='utf-8')))
        print('材料', j, len(msg), flush=True); r = None
        for k in range(3):
            try: r = parse(call(f'adv_k24r{rnd}_{j}' + ('' if not k else f'_r{k}'), msg, G56 if j == 'g56' else G6, 'gpt3s', 'public24-adv')); assert r.get('prompt'); break
            except Exception as ex: print('不合格', j, repr(ex)[:150], flush=True); r = None
        if not r: return
        p.write_text(json.dumps(r, ensure_ascii=False, indent=1), encoding='utf-8')
    r = rd(p); tpl = r['prompt'].replace('{{', '{').replace('}}', '}')
    try: prompt_lint.lint(re.sub(r'\{(BUDGET|DAGSTD|FINAL|BEADS|CURRENT)\}', '', tpl), f'adv_k24r{rnd}_{j}')
    except SystemExit as ex: print('泛化检查没过', j, ex, flush=True)
    (S/f'prompt_K24r{rnd}_{j}.txt').write_text(tpl, encoding='utf-8')
    if r.get('repair_prompt'):
        rp = r['repair_prompt'].replace('{{', '{').replace('}}', '}')
        try: prompt_lint.lint(re.sub(r'\{(SCREEN|ISSUES|BUDGET|DAGSTD|FINAL|BEADS)\}', '', rp), f'adv_k24r{rnd}_{j}_repair')
        except SystemExit as ex: print('修补提示词泛化检查没过', j, ex, flush=True)
        (S/f'prompt_K24r{rnd}_{j}_repair.txt').write_text(rp, encoding='utf-8')
    print(f"== {j}：{r.get('verdict')}；{(r.get('changes') or '')[:900]}", flush=True)


