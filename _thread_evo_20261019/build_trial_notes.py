"""Generate prompt -> complete product differences -> bound evidence notes."""
import difflib
import argparse
import json
import sys

import round54_candidates as R
import build_version_comparison as C


def build(tag):
    B = R.B
    candidates = R.ROOT / 'candidates.json'
    if candidates.exists():
        manifest = json.loads(candidates.read_text(encoding='utf-8'))
        candidate = next(c for c in manifest['candidates'] if c['tag'] == tag)
    else:
        manifest = json.loads((R.ROOT / f'{tag}_manifest.json').read_text(encoding='utf-8'))
        assert manifest['target'] == tag and manifest['base'] == R.BASE
        source = json.loads((R.ROOT.parent / 'round55_current' / 'candidates.json').read_text(encoding='utf-8'))
        original = next(c for c in source['candidates'] if c['tag'] == manifest['revised'])
        assert manifest['prompt_source'] == original['feedback_continuation']['step']
        candidate = {**original, 'steps': [manifest['prompt_source']]}
    applied = R.ROOT / f'{tag}_applied.json'
    assert applied.exists(), 'Only actual paired products get product-difference notes'
    receipt = json.loads(applied.read_text(encoding='utf-8'))
    md = ['<!-- Generated by build_trial_notes.py; do not hand edit. -->',
          f'## {tag} 对 {R.BASE}：{candidate["name"]}', '',
          '### 提示词改动', '', candidate['hypothesis'], '',
          '风险（顾问原文）：' + candidate['risk'], '']
    for step in candidate['steps']:
        p = B.ROOT / step['path']
        assert B.digest(p.read_text(encoding='utf-8')) == step['sha256']
        md += [f'- {step["id"]}：{C.link(p, "通用提示词原文")}；SHA256 `{step["sha256"]}`。']
    md += ['', f'模型原文机械套用记录：{C.link(applied)}。', '', '### 实际测量与处置', '']
    state = C.comparison(tag, R.BASE)
    if state['rows']:
        n = len(state['rows'])
        md += [f'已完整阅读并绑定实际两版输入 {n}/8 票；选新版 {state["wins"]}/{n}，不退步 {state["no_regress"]}/{n}；四维净胜总和 ' +
               '/'.join(f'{state["net_sums"][k]:+d}' for k in B.F.DIMENSIONS) + '。']
    disposition = R.ROOT / f'{tag}_disposition.json'
    final_disposition = R.ROOT / f'{tag}_final_disposition.json'
    if not final_disposition.exists() and manifest.get('target') == tag and manifest.get('revised'):
        # A continuation receipt lives with the shared runner; its original
        # candidate batch retains the final disposition.
        continuation_disposition = R.ROOT.parent / 'round55_current' / f'{tag}_final_disposition.json'
        if continuation_disposition.exists():
            checked = json.loads(continuation_disposition.read_text(encoding='utf-8'))
            assert checked['actual_comparison_base'] == R.BASE
            final_disposition = continuation_disposition
    if final_disposition.exists():
        disposition = final_disposition
    if disposition.exists():
        md += [f'正式处置及完整原票哈希：{C.link(disposition)}。']
    else:
        accepted = B.ROOT / 'runs/_batches/round50_from_r49b' / f'{tag}_acceptance.json'
        if accepted.exists():
            evidence = json.loads(accepted.read_text(encoding='utf-8'))
            assert evidence['base'] == R.BASE and evidence['fair']['pass'] and evidence['floor']['status'] == 'pass'
            md += [f'已正式验收，原盲比及底线记录：{C.link(accepted)}。']
        else:
            md += ['候选仍在测量，尚无验收结论；缺测不计0。']
    for work in B.F.WORKS:
        source = receipt['source_rids'][work]
        assert B.reviewed(source)
        assert receipt['source_output_hashes'][work] == B.digest(B.evo.output(source))
        md += ['', f'### {work} 全部前后差别', '',
               f'模型完整原文：{C.link(B.evo.RUNS / source / "output.txt")}。', '', '```diff']
        old = B.V.view(B.V.graph_of(work, R.BASE), ids=True).splitlines()
        new = B.V.view(B.V.graph_of(work, tag), ids=True).splitlines()
        md += list(difflib.unified_diff(old, new, fromfile=R.BASE, tofile=tag, lineterm=''))
        md += ['```', '']
    output = B.ROOT / '版本说明' / f'{tag}_vs_{R.BASE}.md'
    output.write_bytes('\n'.join(md).encode('utf-8'))
    print(output)


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('tags', nargs='+')
    parser.add_argument('--base', default=R.BASE)
    parser.add_argument('--batch', default=R.ROOT.name)
    args = parser.parse_args()
    for value in (args.base, args.batch):
        R.B.pipe.token(value, 'base/batch')
    R.BASE = args.base
    R.ROOT = R.B.ROOT / 'runs/_batches' / args.batch
    for tag in args.tags:
        build(tag)
