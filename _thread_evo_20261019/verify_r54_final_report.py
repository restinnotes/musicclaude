"""Post-generation verification of the requested final artifact and its sources."""
import hashlib
import json
import re
import tomllib
from datetime import datetime
from zoneinfo import ZoneInfo
from pathlib import Path
import experiment_batch as B
import build_version_comparison as C

root = B.ROOT
audit_path = root / 'runs/_batches/i14_after_r62/convergence_audit.json'
audit = json.loads(audit_path.read_text(encoding='utf-8'))
report = root / '最终版本_vs_r49b.md'
text = report.read_text(encoding='utf-8')
receipt_path = report.with_suffix('.receipt.json')
receipt = json.loads(receipt_path.read_text(encoding='utf-8'))
assert audit['status'] == 'verified' and all(r['status'] == 'proven' for r in audit['requirements'])
assert receipt['phase'] == 'final' and receipt['tag'] == 'r54weave' and receipt['base'] == 'r49b'
assert B.digest(text) == receipt['report_sha256']
assert receipt['model_calls'] == receipt['product_mutations'] == 0
assert text.startswith('<!-- Generated by build_version_comparison.py; do not hand edit. -->\n# 最终版本：r54weave vs r49b')
for group in (audit['source_hashes'], receipt['source_text_sha256']):
    for path, expected in group.items():
        assert B.digest((root / path).read_text(encoding='utf-8')) == expected, path
segments = 0
for work in B.F.WORKS:
    old, new = B.V.graph_of(work, 'r49b'), B.V.graph_of(work, 'r54weave')
    assert len(old['segments']) == len(new['segments'])
    for before, after in zip(old['segments'], new['segments']):
        assert f"#### {before['sec']}｜{before['bars']} 小节" in text
        assert '\n'.join(C.segment_lines(before)) in text
        assert '\n'.join(C.segment_lines(after)) in text
        segments += 1
assert segments == 27 and len(receipt['changes']['op60']['body']) == 14 and len(receipt['changes']['op61']['body']) == 13
assert receipt['comparison']['wins'] == 5 and receipt['comparison']['no_regress'] == 4
assert receipt['comparison']['net_sums'] == {'alone': 26, 'lean': -6, 'plain': 0, 'cover': 12}
assert '按原完整门槛计算：**未通过**' in text
assert '当前版正式验收的实际基准是 `r50progress1rr`' in text
assert '不证明旧问题全部解决或当前版为全局最优' in text
assert 'i14_after_r59' in text and 'i14_after_r62' in text and 'specific_subfinding_resolution.json' in text
assert text.count('```') % 2 == 0 and text.count('<details>') == text.count('</details>')
for target in re.findall(r'\]\(<([A-Za-z]:/[^>]+)>\)', text):
    assert Path(target).exists(), target
pack = json.loads((root / 'runs/_reports/video_pack_r54weave.json').read_text(encoding='utf-8'))
assert hashlib.sha256(Path(pack['zip']).read_bytes()).hexdigest() == pack['zip_sha256']
automation = tomllib.loads(Path('C:/Users/zuoyi/.codex/automations/automation/automation.toml').read_text(encoding='utf-8'))
assert automation['status'] == 'PAUSED'
proof = {
    'status': 'verified', 'verified_at': datetime.now(ZoneInfo('America/New_York')).isoformat(),
    'objective': '继续迭代直到收敛 最后生成最后版本vsr49b的md',
    'final_version': 'r54weave', 'comparison_base': 'r49b',
    'convergence_audit': str(audit_path.relative_to(root)),
    'convergence_audit_sha256': B.digest(audit_path.read_text(encoding='utf-8')),
    'all_eight_convergence_and_delivery_requirements_proven': True,
    'final_report': str(report.relative_to(root)), 'final_report_sha256': receipt['report_sha256'],
    'script_generated': True, 'all_27_before_after_segments_verified': True,
    'all_report_sources_and_local_links_verified_current': True,
    'direct_comparison_gate_failure_explicit': True, 'all_original_ratings_and_dissent_retained': True,
    'zip_unchanged': True, 'heartbeat_status': 'PAUSED',
    'limitations': audit['limitations'], 'quality_compliance_proven': False,
    'required_remaining': [], 'model_calls': 0,
}
path = root / 'runs/_batches/i14_after_r62/final_report_verification.json'
B.write_frozen(path, B.json_text(proof))
print(B.json_text({'verified': True, 'report': str(report), 'segments': segments,
                   'sha256': receipt['report_sha256'], 'quality_compliance_proven': False, 'required_remaining': []}))
